public class AForMultiposDe3Ate30 {
    public static void main(String[] args) {

        System.out.println("\nFOR: \n");

        for (int i = 3; i <= 30; i += 3) {
            System.out.println("Multipos de 3: " + i);

        }
        System.out.println("\nWHILE: \n");

        int i = 3;

        while (i <= 30) {

            System.out.println("Multipos de 3: " + i);

            i += 3;

        }

    }
}
